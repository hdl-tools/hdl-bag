"""The user manual (D99, Phase 6 PR 2): its rules, and the tests that hold it to them.

The manual is LaTeX source in the repository (after hdl-vet's, ../hdl-vet/docs/manual);
CI builds the PDF. Its reader is an RTL or SoC engineer who has never used BAG. English is
not the first language of many readers. The owner's rule: every example a reader sees is
run by a test.

LAYOUT (all under `docs/manual`)

    hdl-bag.tex            the main file: preamble, title, contents, \\input of the chapters
    version.tex            one line: \\newcommand{\\bagversion}{<hdl_bag.__version__>}
    checks.tex             every check rule, generated (see M6)
    chapters/*.tex         the text
    examples/console/      console transcripts the host test replays (tests/manual/transcript.py)
    examples/console/eda/  transcripts that run EDA tools; the EDA test replays them
    examples/files/        other files the manual shows (inputs a transcript copies in)

`.gitattributes` keeps `docs/manual/` on LF line ends on every machine.

RULES THE TESTS CHECK

M1  Version. `version.tex` is exactly the line above, and no other `.tex` file contains the
    version. The manual prints the version through \\bagversion, except in the IR examples
    under `examples/files/`, whose provenance records the version that produced them: those
    carry `hdl_bag.__version__`, so a release bump cannot leave the IR chapter showing an
    old one.
M2  Every file named by \\input, \\include, \\lstinputlisting or \\includegraphics exists,
    with the same spelling (CI builds on Linux). Paths are relative to `docs/manual`.
M3  No example is typed into the text: the environments lstlisting, verbatim, Verbatim,
    minted and alltt, and \\verbatiminput, are not used. Code and output are shown with
    \\lstinputlisting from a file under `examples/`. Short names inside a sentence are fine.
M4  Nothing under `examples/` is unused: the manual shows every transcript and file with
    \\lstinputlisting, except an input a transcript only copies or reads.
M5  Every transcript replays exactly and runs `bag` at least once. Host transcripts run in
    every host test run; those under `eda/` in the EDA test.
M6  Checks. `checks.tex` is exactly: a comment line "% Generated by tests/manual/test_manual.py
    from hdl_bag.checks.core and the broken-workbook cases; rewrite it with
    BAG_MANUAL_UPDATE=1." and then, sorted by rule ID, one line
    \\checkrule{ID}{severity}{message} for every rule in RULES, where the message is the
    first one its broken-workbook case gives (tests/checks/test_checks.py CASES), so the
    table shows each rule as a user reads it and cannot drift.
M7  Command line. Every `bag` command appears as \\cmd{bag <name>}, and every long option
    of every command as \\opt{--name}, in chapters/cli.tex.
M8  Workbook. chapters/workbook.tex names every sheet with \\sheet{...}, every input column
    of every table (hdl_bag.reader.workbook.TABLES) with \\col{...}, and every Project and
    Wrapper setting of the blank template with \\setting{...}.
M9  Only the packages in PACKAGES are loaded, so the manual builds the same with TeX Live
    (CI) and MiKTeX. The preamble has \\DisableLigatures[-]{encoding = T1, family = tt*}:
    without it `--formal` prints with a dash that cannot be copied.
M10 The `.tex` files and the examples are ASCII, and contain no TODO, TBD, FIXME or XXX.
M11 `.github/workflows/manual.yml` builds the PDF on pull requests and pushes to main that
    touch `docs/manual/**` or the workflow, and on workflow_dispatch and workflow_call; on
    ubuntu-24.04 with TeX Live from apt (lmodern named), with
    `latexmk -pdf -interaction=nonstopmode -halt-on-error hdl-bag.tex`, failing when the
    log reports an undefined or multiply defined reference, and uploading `hdl-bag.pdf` as
    the artifact `hdl-bag-manual`. Only actions/checkout and actions/upload-artifact. LaTeX
    build products are ignored by git.
M12 Tool versions. Every version the manual prints is the pinned one: the table of
    chapters/install.tex against `tools.lock`, and every SymbiYosys version any chapter states
    against `SymbiYosys.pinned`, which is authoritative because the suite's SymbiYosys version
    is not in the lock. A bump already fails the pins in `flows/backends.py` and the ARG
    defaults in `tools/Dockerfile`, which is where a bumper looks, and `formal.py`'s comment
    names install.tex -- but nothing read the manual, so each of these could be left stale in
    a document published as a PDF, and flows.tex is named nowhere at all.

WHAT THE TESTS CANNOT CHECK (the reviewer does)

W1  Every statement is true of the code today. The code wins over the plan and over the
    private spec guide (design/spec-workbook-guide.md); differences are reported.
W2  Plain words: short sentences, present tense, "you". A term is defined where it first
    appears and used with one meaning (workbook, spec, IR, fabric, port, adapter, bridge,
    region, check, rule ID, output directory, job, task). No marketing.
W3  Nothing is promised that does not exist. What is missing is in the limits chapter.
W4  The PDF builds without errors, undefined references or overfull boxes wider than the
    margin, on TeX Live and on MiKTeX.

OUTLINE (chapter files in this order; content may not be less)

 1  intro: what BAG is for; the pipeline workbook -> check -> IR -> generate -> lint ->
    compile -> sim -> formal; what is generated; deterministic output; what BAG does not do.
 2  install: Python 3.11+; from PyPI, a git URL or a checkout; the `sim`
    extra; the EDA tools and the pinned versions (tools.lock), the tools image.
 3  first: the demo_ss sample start to finish: template, check (its two warnings and why),
    ir, generate, the output tree; lint, sim and formal on a small design (EDA transcripts).
 4  workbook: every sheet, column and setting, with legal values and what each means
    (the public version of the spec guide at schema 0.7).
 5  checks: how a finding reads (sheet, row, rule ID), errors and warnings, and the
    generated table of every rule.
 6  ir: the YAML IR as the contract; schema version; a workbook and an IR as inputs; an
    edited IR is checked as the workbook it converts to.
 7  outputs: every file `bag generate` writes and what it is for (RTL, package, wrapper,
    file list, C header, docs, tie-offs, reset sequence, tests, formal jobs, manifest).
 8  flows: lint (tools, waivers, third-party findings), compile, sim (generated tests,
    coverage report, the READY shim), formal (jobs, tasks, bounds, timeouts).
 9  cli: every command and option, and the exit statuses.
10  limits: the known limits (plan/phase-6.md scope 5), each checked against the code.
"""

import re
import shlex
from pathlib import Path

import openpyxl
import pytest
import transcript

from hdl_bag import __version__
from hdl_bag.checks.core import RULES
from hdl_bag.flows.formal import SymbiYosys
from hdl_bag.reader.workbook import HDR_ROW, TABLES
from hdl_bag.template.builder import build_workbook

MANUAL = transcript.MANUAL
CHAPTERS = MANUAL / "chapters"
EXAMPLES = transcript.EXAMPLES
CONSOLE = EXAMPLES / "console"
EDA = CONSOLE / "eda"

PACKAGES = (
    "fontenc", "inputenc", "lmodern", "textcomp", "microtype", "geometry", "parskip",
    "xcolor", "array", "booktabs", "tabularx", "longtable", "enumitem", "caption",
    "fancyhdr", "upquote", "listings", "hyperref",
)  # fmt: skip
CHECKS_HEADER = ("% Generated by tests/manual/test_manual.py from hdl_bag.checks.core and the "
                 "broken-workbook cases; rewrite it with BAG_MANUAL_UPDATE=1.")  # fmt: skip


def _tex_files() -> list[Path]:
    return sorted(MANUAL.glob("*.tex")) + sorted(CHAPTERS.glob("*.tex"))


def _text() -> str:
    return "\n".join(p.read_text(encoding="utf-8") for p in _tex_files())


def _uncommented(text: str) -> str:
    return re.sub(r"(?<!\\)%.*", "", text)


def test_version_is_the_package_version() -> None:
    """M1."""
    assert (MANUAL / "version.tex").read_text(encoding="utf-8") == (
        f"\\newcommand{{\\bagversion}}{{{__version__}}}\n"
    )
    others = [q for q in _tex_files() if q.name != "version.tex"]
    assert not [q.name for q in others
                if __version__ in _uncommented(q.read_text(encoding="utf-8"))]  # fmt: skip


def test_the_example_ir_files_record_the_current_version() -> None:
    """M1: chapters/ir.tex shows an example IR whole, provenance included, so these files print
    the version to the reader. Nothing else catches them going stale, because the transcripts'
    IR sha256 lines move only once these files do."""
    want = f"bag_version: {__version__}"
    seen = [
        (p.name, line.strip())
        for p in sorted((MANUAL / "examples" / "files").glob("*.ir.yaml"))
        for line in p.read_text(encoding="utf-8").splitlines()
        if line.strip().startswith("bag_version:")
    ]
    assert len(seen) >= 6, f"one bag_version line per IR example was expected, found {seen}"
    stale = {name: line for name, line in seen if line != want}
    assert not stale, f"regenerate these with the current version ({__version__}): {stale}"


def _referenced() -> list[str]:
    pattern = r"\\(?:input|include|lstinputlisting|includegraphics)(?:\[[^\]]*\])?\{([^}]+)\}"
    return re.findall(pattern, _uncommented(_text()))


def test_every_referenced_file_exists_with_its_spelling() -> None:
    """M2."""
    missing = []
    for ref in _referenced():
        path = MANUAL / (ref if Path(ref).suffix else f"{ref}.tex")
        names = {p.name for p in path.parent.iterdir()} if path.parent.is_dir() else set()
        if path.name not in names:
            missing.append(ref)
    assert missing == []


def test_no_example_is_typed_into_the_text() -> None:
    """M3."""
    text = _uncommented(_text())
    found = re.findall(r"\\begin\{(lstlisting|verbatim|Verbatim|minted|alltt)\}|\\verbatiminput",
                       text)  # fmt: skip
    assert found == []


def _copied_or_read() -> set[str]:
    """Example files a transcript only copies in or reads (paths relative to examples/)."""
    used: set[str] = set()
    for t in sorted(CONSOLE.rglob("*.txt")):
        for command in transcript.commands(t.read_text(encoding="utf-8")):
            words = shlex.split(command)
            if words[0] in ("cp", "cat", "bag"):
                used |= {w for w in words[1:] if not w.startswith("-")}
    return used


def test_every_example_is_shown() -> None:
    """M4."""
    shown = {r.removeprefix("examples/") for r in _referenced() if r.startswith("examples/")}
    files = {p.relative_to(EXAMPLES).as_posix() for p in EXAMPLES.rglob("*") if p.is_file()}
    assert files - shown - _copied_or_read() == set()


def _transcripts(eda: bool) -> list[Path]:
    found = sorted(CONSOLE.rglob("*.txt"))
    return [t for t in found if (EDA in t.parents) == eda]


@pytest.mark.parametrize("path", _transcripts(False), ids=lambda p: p.stem)
def test_a_transcript_replays(path: Path, tmp_path: Path) -> None:
    """M5, host part."""
    expected, actual = transcript.replay(path, tmp_path)
    assert any(c.startswith("bag ") for c in transcript.commands(expected))
    assert actual == expected


@pytest.mark.eda
@pytest.mark.parametrize("path", _transcripts(True), ids=lambda p: p.stem)
def test_an_eda_transcript_replays(path: Path, tmp_path: Path) -> None:
    """M5, EDA part."""
    expected, actual = transcript.replay(path, tmp_path, eda=True)
    assert any(c.startswith("bag ") for c in transcript.commands(expected))
    assert actual == expected


def _latex(text: str) -> str:
    """TEXT safe inside a tabular cell set in \\ttfamily."""
    out = []
    for ch in text:
        out.append({
            "\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&",
            "#": r"\#", "^": r"\^{}", "_": r"\_", "%": r"\%", "~": r"\~{}",
        }.get(ch, ch))  # fmt: skip
    return "".join(out)


def _checks_tex() -> str:
    from test_checks import CASES

    first = {}
    for rule, _, messages in CASES:
        if rule not in first and messages:
            first[rule] = messages[0]
    lines = [CHECKS_HEADER]
    for rule in sorted(RULES):
        severity = RULES[rule].value if hasattr(RULES[rule], "value") else str(RULES[rule])
        lines.append(f"\\checkrule{{{rule}}}{{{severity}}}{{{_latex(first[rule])}}}")
    return "\n".join(lines) + "\n"


def test_the_check_table_is_generated_from_the_rules() -> None:
    """M6."""
    path = MANUAL / "checks.tex"
    want = _checks_tex()
    if transcript.UPDATE and (not path.is_file() or path.read_text(encoding="utf-8") != want):
        path.write_bytes(want.encode("ascii"))
    assert path.read_text(encoding="utf-8") == want


def _commands() -> dict[str, list[str]]:
    from hdl_bag.cli import main

    return {name: [o for p in cmd.params for o in getattr(p, "opts", []) if o.startswith("--")]
            for name, cmd in main.commands.items()}  # fmt: skip


def test_every_command_and_option_is_in_the_cli_chapter() -> None:
    """M7."""
    text = (CHAPTERS / "cli.tex").read_text(encoding="utf-8")
    missing = []
    for name, options in _commands().items():
        missing += [f"bag {name}"] if f"\\cmd{{bag {name}}}" not in text else []
        missing += [o for o in options if f"\\opt{{{o}}}" not in text]
    assert missing == []


def _settings() -> dict[str, list[str]]:
    """The Setting column of the blank template's Project and Wrapper sheets."""
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "blank.xlsx"
        build_workbook(sample=False).save(path)
        wb = openpyxl.load_workbook(path)
        out = {}
        for sheet in ("Project", "Wrapper"):
            ws = wb[sheet]
            names = []
            for row in range(HDR_ROW + 1, ws.max_row + 1):
                value = ws.cell(row, 1).value
                if not isinstance(value, str) or not value.strip():
                    break
                names.append(value.strip())
            out[sheet] = names
        return out


def test_every_sheet_column_and_setting_is_in_the_workbook_chapter() -> None:
    """M8."""
    text = (CHAPTERS / "workbook.tex").read_text(encoding="utf-8")
    wanted = {f"\\sheet{{{t.sheet}}}" for t in TABLES} | {"\\sheet{Project}", "\\sheet{Wrapper}"}
    wanted |= {f"\\col{{{h}}}" for t in TABLES for h in t.headers}
    wanted |= {f"\\setting{{{s}}}" for names in _settings().values() for s in names}
    assert sorted(w for w in wanted if w not in text) == []


def _flow_rules() -> set[str]:
    """Rule IDs the flows, generated tests and formal give (findings that are not checks)."""
    src = transcript.REPO / "src" / "hdl_bag"
    found: set[str] = set()
    for folder in ("flows", "tests_gen", "formal_gen"):
        for path in (src / folder).rglob("*.py"):
            found |= set(re.findall(r'"([A-Z]+(?:-[A-Z0-9]+)+)"', path.read_text(encoding="utf-8")))
    return found


def test_every_rule_id_named_is_real() -> None:
    """A rule ID in the text is a check rule or a rule a flow reports (PR 109 review: an
    example named TOPO-INDEX-RANGE, which does not exist)."""
    chapters = "\n".join(p.read_text(encoding="utf-8") for p in sorted(CHAPTERS.glob("*.tex")))
    named = set(re.findall(r"\\ruleid\{([^}]+)\}", _uncommented(chapters)))
    assert sorted(named - set(RULES) - _flow_rules()) == []


def test_only_the_portable_packages_are_loaded() -> None:
    """M9."""
    main = _uncommented((MANUAL / "hdl-bag.tex").read_text(encoding="utf-8"))
    loaded = re.findall(r"\\usepackage(?:\[[^\]]*\])?\{([^}]+)\}", main)
    assert sorted({p.strip() for group in loaded for p in group.split(",")}) == sorted(PACKAGES)
    assert "\\DisableLigatures[-]{encoding = T1, family = tt*}" in main


def test_the_sources_are_ascii_and_finished() -> None:
    """M10."""
    bad = []
    for path in [*_tex_files(), *(p for p in EXAMPLES.rglob("*") if p.is_file())]:
        data = path.read_bytes()
        if any(b > 127 for b in data):
            bad.append(f"{path.name}: not ASCII")
        if re.search(rb"\b(TODO|TBD|FIXME|XXX)\b", data):
            bad.append(f"{path.name}: unfinished")
    assert bad == []


