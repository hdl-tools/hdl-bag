# Timeouts are a few times the longest run seen (the route test on demo_ss, the largest config,
# stays under 1 ms of simulated time), so a deadlocked design fails within minutes instead of
# hanging CI.
async def every_master_reaches_what_the_model_says(dut: Any) -> None:
    # BAG_ROUTE_MASTERS "i/k" checks every k-th master from i (test_corpus.py's ROUTE_PARTS).
    i, k = (int(x) for x in (os.environ.get("BAG_ROUTE_MASTERS") or "0/1").split("/"))
    masters, slaves, _ = await _bring_up(dut)
    secure = any(r.secure for r in SPEC.memory_map)
    checked = errors = 0
    reached: set[str] = set()
    for pins in _pin_sets():
        for x, on in pins.items():
            getattr(dut, x).value = int(on)
        for m in SPEC.masters[i::k]:
            nonsec_options = [False, True] if secure and not prot_tied(SPEC, m.name) else [False]
            for nonsec in nonsec_options:
                for addr in probes(SPEC):
                    if addr >= 1 << m.addr_width:
                        continue
                    data = random.getrandbits(32)
                    written = None
                    for write in (True, False):
                        ns = nonsec
                        if m.protocol == "AHB-Lite":
                            prot = random.getrandbits(4)
                        else:
                            # Without secure regions the non-secure bit cannot change the
                            # route, so it is random too and every PROT bit is checked.
                            ns = nonsec if secure else bool(random.getrandbits(1))
                            prot = (random.getrandbits(3) & ~0b010) | int(ns) << 1
                        exp = route(SPEC, m.name, addr, write, ns, pins)
                        before = {n: len(s.log) for n, s in slaves.items()}
                        stored = {n: len(s.written) for n, s in slaves.items()}
                        user = random.getrandbits(m.user_width) if m.user_width else 0
                        err, got, resp = await _access(masters[m.name], m.protocol,
                                                       m.data_width, addr, write, data, nonsec,
                                                       prot, user)  # fmt: skip
                        want_resp = _expected_resp(m, exp, write)
                        where = f"{m.name} {'W' if write else 'R'} {addr:#x} nonsec={nonsec} pins={pins}"
                        grew = {n for n, s in slaves.items() if len(s.log) != before[n]}
                        if exp.slave is None:
                            assert err == (not exp.masked) and not grew, (
                                f"{where}: expected {'a masked' if exp.masked else 'an'} error, "
                                f"got err={err} at {grew}"
                            )
                            assert want_resp is None or resp == want_resp, (
                                f"{where}: response {resp}, expected {want_resp} ({exp.miss})"
                            )
                        else:
                            assert err == exp.slave_error and grew == {exp.slave}, (
                                f"{where}: expected {exp.slave} @ {exp.address:#x} "
                                f"error={exp.slave_error}, got err={err} at {grew}"
                            )
                            # A width converter may add beats (zero-strobe halves), so the
                            # access must be among what the slave saw, not necessarily last.
                            new = slaves[exp.slave].log[before[exp.slave] :]
                            match = [e for e in new if e.addr == exp.address and e.write == write]
                            assert match, (
                                f"{where}: {exp.slave} saw {[hex(e.addr) for e in new]} "
                                f"write={write}, expected {exp.address:#x}"
                            )
                            # APB transfers cost time and can have side effects: one
                            # that stores nothing has no reason to exist.
                            is_apb = next(
                                x.protocol for x in SPEC.slaves if x.name == exp.slave
                            ) in ("APB3", "APB4")
                            assert not (is_apb and any(e.write and not e.strb for e in new)), (
                                f"{where}: an APB write with no strobes"
                            )
                            if write:
                                check_write(where, exp, data.to_bytes(4, "little"),
                                            slaves[exp.slave].written[stored[exp.slave] :])  # fmt: skip
                            else:
                                check_read(where, exp, 4, _read_beats(new, exp.word_bytes))
                            seen = match[0]
                            assert want_resp is None or resp == want_resp, (
                                f"{where}: response {resp}, expected {want_resp}"
                            )
                            s_uw = next(x.user_width for x in SPEC.slaves if x.name == exp.slave)
                            if m.user_width and s_uw and not exp.bridges:
                                want_user = user & ((1 << s_uw) - 1)
                                assert seen.user == want_user, (
                                    f"{where}: {exp.slave} saw USER {seen.user:#x}, "
                                    f"expected {want_user:#x}"
                                )
                            want = _expected_prot(m, exp.slave, prot, exp.nonsec, exp.bridges)
                            assert want is None or seen.prot == want, (
                                f"{where}: {exp.slave} saw PROT {seen.prot:#b}, expected {want:#b}"
                            )
                            cache = getattr(seen, "cache", None)  # AXI4 slaves only
                            want_cache = _expected_cache(m, prot, exp.nonsec, exp.bridges)
                            assert cache is None or cache == want_cache, (
                                f"{where}: {exp.slave} saw AxCACHE {cache:#b}, "
                                f"expected {want_cache:#b}"
                            )
                            errors += exp.slave_error
                            if write and not exp.slave_error:
                                written = exp
                            elif not write and written == exp and not exp.slave_error:
                                assert got == data, f"{where}: read {got:#x}, wrote {data:#x}"
                        checked += 1
                        reached.add(m.name)
                        for kind, key in coverage.access_bins(SPEC, m, addr, write, nonsec, exp):
                            coverage.hit(kind, key)
    assert checked > 0 and errors > 0, (checked, errors)
    assert reached == {m.name for m in SPEC.masters[i::k]}, reached
    dut._log.info("checked %d accesses (%d slave errors)", checked, errors)


async def arbitration_follows_the_fabric_policy(dut: Any) -> None:
    masters, slaves, _ = await _bring_up(dut)
    checked = 0
    for f in SPEC.fabrics:
        # The region the most masters can address and write directly; those masters write it
        # at a distinct word each.
        found = contention(SPEC, f, secure_too=True) if f.protocol == "AHB-Lite" else None
        if found is None:
            continue
        region, ports = found
        width = next(s.addr_width for s in SPEC.slaves if s.name == region.slave)
        addrs = {p.port: region.base + 16 * i for i, p in enumerate(ports)}
        visible = {(a & ((1 << width) - 1)): p for p, a in addrs.items()}
        n = len(slaves[region.slave].log)
        await Combine(*(cocotb.start_soon(_access(masters[p], "AHB-Lite", 32, a, True, i, False, 3))
                        for i, (p, a) in enumerate(addrs.items())))  # fmt: skip
        order = [visible[e.addr] for e in slaves[region.slave].log[n:] if e.write]
        if f.arbitration == "fixed-priority":
            want = [p.port for p in sorted(ports, key=lambda p: p.priority or 0)]
            assert order == want, f"{f.name}: served {order}, priority order {want}"
        else:
            assert sorted(order) == sorted(addrs), f"{f.name}: served {order}"
        dut._log.info("%s (%s): served %s", f.name, f.arbitration, order)
        checked += 1
    assert checked > 0


async def _traffic(masters: dict[str, Any], spawned: list[Any] | None = None) -> tuple[int, int]:
    """All masters at once, AXI masters with several transactions in flight (cocotbext-axi
    rotates IDs): every write lands and every read returns that master's own data. Returns the
    words checked and the masters that took part. Every task it starts goes in SPAWNED, so a
    caller can abandon all of them (a reset)."""
    spawned = [] if spawned is None else spawned

    def start(coro: Any) -> Any:
        task = cocotb.start_soon(coro)
        spawned.append(task)
        return task

    async def traffic(m: Any, words: list[int]) -> int:
        data = {a: random.getrandbits(32) for a in words}
        if m.protocol in AXI:
            writes = [start(masters[m.name].write(a, d)) for a, d in data.items()]
            await Combine(*writes)
            assert not any(w.result() for w in writes), f"{m.name}: write error"
            reads = [start(masters[m.name].read(a)) for a in data]
            await Combine(*reads)
            got = [r.result() for r in reads]
        else:
            prot = 3 if m.protocol == "AHB-Lite" else 0  # secure (APB: PPROT[1] = non-secure)
            for a, d in data.items():
                err, _, _ = await _access(masters[m.name], m.protocol, m.data_width, a, True,
                                          d, False, prot)  # fmt: skip
                assert not err, f"{m.name}: write error at {a:#x}"
            got = []
            for a in data:
                err, value, _ = await _access(masters[m.name], m.protocol, m.data_width, a,
                                              False, 0, False, prot)  # fmt: skip
                got.append(type("R", (), {"err": err, "data": value})())
        for (a, d), r in zip(data.items(), got, strict=True):
            assert not r.err and r.data == d, f"{m.name} {a:#x}: read {r.data:#x}, wrote {d:#x}"
        return len(data)

    plans = {m.name: (m, private_words(SPEC, m, i, 8)) for i, m in enumerate(SPEC.masters)}
    tasks = [start(traffic(m, words)) for m, words in plans.values() if words]
    await Combine(*tasks)
    total = sum(t.result() for t in tasks)
    assert total > 0
    return total, len(tasks)


async def concurrent_traffic_keeps_every_masters_data(dut: Any) -> None:
    """Every master's own words, all at once (_traffic)."""
    masters, _, _ = await _bring_up(dut)
    total, count = await _traffic(masters)
    dut._log.info("concurrent traffic: %d words over %d masters", total, count)


async def _bursts(
    masters: dict[str, Any], spawned: list[Any] | None = None, offset: int = 0
) -> int:
    """Every AXI4 master at once: an 8-beat INCR burst of its own words, written and read back.
    OFFSET moves the words (private_words' index) clear of _traffic's, so both can run at once.
    Every task it starts goes in SPAWNED. Returns the bursts checked."""

    async def one(m: Any, word: int) -> None:
        data = bytes(random.getrandbits(8) for _ in range(32))
        assert await masters[m.name].burst_write(word, data) == 0, f"{m.name} burst write"
        r = await masters[m.name].burst_read(word, 32)
        assert not r.err and r.data == int.from_bytes(data, "little"), f"{m.name} burst read"

    count = len(SPEC.masters)
    plans = [(m, private_words(SPEC, m, i + offset * count, 8)) for i, m in enumerate(SPEC.masters)
             if m.protocol == "AXI4"]  # fmt: skip
    tasks = [cocotb.start_soon(one(m, words[0])) for m, words in plans if words]
    if spawned is not None:
        spawned += tasks
    if tasks:
        await Combine(*tasks)
    return len(tasks)


async def traffic_survives_back_pressure_on_every_channel(dut: Any) -> None:
    """All masters at once under random gaps, single beats and then bursts: on AXI, every channel
    of every port, at the slaves only, then the masters only, then both; AHB-Lite and APB slaves
    wait longer with the slaves' gaps. (The AHB-Lite and APB master models add no gaps of their
    own.) A design that loses a beat or a response under stalls returns wrong data or times out."""
    masters, slaves, _ = await _bring_up(dut)
    seed = 1
    for at_slaves, at_masters in ((True, False), (False, True), (True, True)):
        for ports, on in ((slaves.values(), at_slaves), (masters.values(), at_masters)):
            for port in ports:
                seed += 1
                if hasattr(port, "pause"):
                    port.pause(seed) if on else port.resume()
                elif hasattr(port, "max_wait"):
                    port.max_wait = 4 if on else 1
        total, count = await _traffic(masters)
        bursts = await _bursts(masters)
        dut._log.info("back-pressure at slaves=%s masters=%s: %d words over %d masters, %d bursts",
                      at_slaves, at_masters, total, count, bursts)  # fmt: skip


def _set_resets(dut: Any, asserted: bool) -> None:
    for r in SPEC.resets:
        level = asserted if r.polarity != "active-low" else not asserted
        getattr(dut, r.name).value = int(level)


async def _cycles(clocks: dict[str, Any], n: int) -> None:
    """At least N cycles of every clock."""
    for clk in clocks.values():
        await ClockCycles(clk, n)


def _busy(name: str, model: Any) -> dict[str, int]:
    """What model NAME is being asked to do by the design: any request or response VALID (AW,
    W, AR towards an AXI slave; B, R towards an AXI master; HTRANS towards an AHB-Lite slave;
    PSEL towards an APB slave), or HREADY low towards an AHB-Lite master (it is high in reset)."""
    if hasattr(model, "bus") and hasattr(model, "target"):  # AXI slave
        w, r = model.bus.write, model.bus.read
        return {f"{name}.awvalid": int(w.aw.awvalid.value), f"{name}.wvalid": int(w.w.wvalid.value),
                f"{name}.arvalid": int(r.ar.arvalid.value)}  # fmt: skip
    if hasattr(model, "bus"):  # AXI master
        return {f"{name}.bvalid": int(model.bus.write.b.bvalid.value),
                f"{name}.rvalid": int(model.bus.read.r.rvalid.value)}  # fmt: skip
    if isinstance(model, AhbSlave):
        return {f"{name}.htrans": model.port["htrans"]}
    if isinstance(model, ApbSlave):
        return {f"{name}.psel": model.port["psel"]}
    if isinstance(model, AhbMaster):
        return {f"{name}.hready_low": 1 - model.p["hready"]}
    return {}


async def _watch_reset(dut: Any, masters: dict[str, Any], slaves: dict[str, Any],
                       held: list[bool], seen: list[str]) -> None:  # fmt: skip
    """While HELD[0], on every edge of every domain's own clock, record in SEEN anything that
    asks a model to act. Each domain gets the latency of its own reset: bag_rst_sync clears its
    flops at once (async), so nothing from the first edge on; or after its 2 stages (sync), so
    from the third."""
    ports = {**{m.name: (m.domain, masters[m.name]) for m in SPEC.masters},
             **{s.name: (s.domain, slaves[s.name]) for s in SPEC.slaves}}  # fmt: skip

    async def domain(name: str, clk: Any, allow: int) -> None:
        mine = [(p, model) for p, (d, model) in ports.items() if d == name]
        edges = 0
        while held[0]:
            await RisingEdge(clk)
            await ReadOnly()
            edges += 1
            if held[0] and edges > allow:
                for p, model in mine:
                    seen.extend(
                        f"{k} at edge {edges} of {name}" for k, v in _busy(p, model).items() if v
                    )

    resets = {r.domain: r for r in SPEC.resets}
    clocks = {c.domain: getattr(dut, c.name) for c in SPEC.clocks}
    tasks = [cocotb.start_soon(domain(d, clk, 0 if resets[d].assertion == "async" else 2))
             for d, clk in clocks.items()]  # fmt: skip
    await Combine(*tasks)


def _activity(masters: dict[str, Any], slaves: dict[str, Any]) -> dict[str, int]:
    """How much every slave has seen and stored, and every response VALID at a master."""
    out = {f"{n}.log": len(s.log) for n, s in slaves.items()}
    out |= {f"{n}.written": len(s.written) for n, s in slaves.items()}
    for n, m in masters.items():
        if hasattr(m, "bus"):
            out |= _busy(n, m)
    return out


async def _reset_everything(
    dut: Any,
    masters: dict[str, Any],
    slaves: dict[str, Any],
    clocks: dict[str, Any],
    tasks: list[Any] | None = None,
) -> None:
    """Assert every reset, as CLK-CDC-RESET requires, and abandon TASKS (traffic in flight).
    While reset is held, nothing may ask a model to act (_watch_reset, every edge). After it,
    with no master asking, nothing may reach a slave and no response may come back: nothing
    left over from before the reset surfaces. Then the models start again."""
    for t in tasks or ():
        t.cancel()
    _set_resets(dut, True)
    for s in slaves.values():
        if hasattr(s, "stop"):
            s.stop()
    for m in masters.values():
        if hasattr(m, "idle"):
            m.idle()
    held: list[bool] = [True]
    seen: list[str] = []
    watch = cocotb.start_soon(_watch_reset(dut, masters, slaves, held, seen))
    await _cycles(clocks, 8)
    await RisingEdge(next(iter(clocks.values())))
    held[0] = False
    _set_resets(dut, False)
    await watch
    assert not seen, f"asked to act during reset: {seen[:6]}"
    await _cycles(clocks, 6)  # bag_rst_sync releases after its stages
    for s in slaves.values():
        if hasattr(s, "stop"):
            s.start()  # listening again, so a leftover transfer is seen
    before = _activity(masters, slaves)
    await _cycles(clocks, 20)  # a quiet spell: no master asks for anything
    after = _activity(masters, slaves)
    changed = {
        k: (before[k], after[k])
        for k in before
        if before[k] != after[k] or (k.endswith(("valid", "hready_low")) and after[k])
    }
    assert not changed, f"after reset, with no master asking: {changed}"


async def _everywhere(masters: dict[str, Any], spawned: list[Any] | None = None) -> int:
    """Every master at once, each to word 0x40 of every slave it reaches cleanly (plain_word),
    through every fabric and bridge on the way: each word written, then all read back. Every
    task it starts goes in SPAWNED. Returns the words checked."""

    async def one(m: Any, words: list[int]) -> int:
        prot = 0b0011 if m.protocol == "AHB-Lite" else 0
        data = {a: random.getrandbits(32) for a in words}
        for a, d in data.items():
            err, _, _ = await _access(
                masters[m.name], m.protocol, m.data_width, a, True, d, False, prot
            )
            assert not err, f"{m.name}: write error at {a:#x}"
        for a, d in data.items():
            err, got, _ = await _access(
                masters[m.name], m.protocol, m.data_width, a, False, 0, False, prot
            )
            assert not err and got == d, f"{m.name} {a:#x}: read {got:#x}, wrote {d:#x}"
        return len(data)

    def own_word(i: int, m: Any, s: Any) -> int | None:
        """A word of S only master I uses: word 0x40 + 16 * I, if M reaches it cleanly too."""
        found = plain_word(SPEC, m, s)
        if found is None:
            return None
        word = found[0] + 16 * i
        outs = [route(SPEC, m.name, word, w, False, {}) for w in (True, False)]
        ok = word < 1 << m.addr_width and all(
            o.slave == s.name and not (o.slave_error or o.masked) for o in outs
        )
        return word if ok else None

    plans = {
        m.name: (m, [w for s in SPEC.slaves if (w := own_word(i, m, s)) is not None])
        for i, m in enumerate(SPEC.masters)
    }
    tasks = [cocotb.start_soon(one(m, words)) for m, words in plans.values() if words]
    if spawned is not None:
        spawned += tasks
    if tasks:
        await Combine(*tasks)
    return sum(t.result() for t in tasks)


async def reset_during_traffic_leaves_nothing_behind(dut: Any) -> None:
    """All masters at once, each to every slave it reaches (_everywhere) and with AXI4 bursts.
    For each slave reached, every reset is asserted on an edge where a request to that slave is
    in the middle of its handshake, so every path, through every bridge on it, is cut
    mid-transfer. While reset is held nothing asks a model to act, on any edge of any domain;
    once it is released nothing left over surfaces; then fresh traffic from every master to
    every slave returns its own data."""
    masters, slaves, clocks = await _bring_up(dut)

    # _bring_up gives the first clock by name DEFAULT_PERIODS[0], the shortest period.
    first = sorted(SPEC.clocks, key=lambda c: c.name)[0]
    fastest = getattr(dut, first.name)

    def mid_handshake(slave: str) -> list[str]:
        return [k for k, v in _busy(slave, slaves[slave]).items() if v]

    # Each slave in turn: wait until a request to it is in the middle of its handshake, and
    # reset on that edge, so every path (through every bridge on it) is cut mid-transfer.
    reached = sorted({s.name for m in SPEC.masters for s in SPEC.slaves if plain_word(SPEC, m, s)})
    for target in reached:
        spawned: list[Any] = []
        work: list[Any] = [
            cocotb.start_soon(_everywhere(masters, spawned)),
            cocotb.start_soon(_bursts(masters, spawned, 1)),
        ]
        mid: list[str] = []
        while not mid:
            assert not all(t.done() for t in work), f"no request to {target} was caught in flight"
            await RisingEdge(fastest)
            await ReadOnly()
            mid = mid_handshake(target)
        await NextTimeStep()  # out of the read-only phase, still in that cycle
        await _reset_everything(dut, masters, slaves, clocks, [*work, *spawned])
        words = await _everywhere(masters)
        bursts = await _bursts(masters)
        dut._log.info("reset with %s mid-handshake: then %d words to every slave reached, %d bursts",
                      mid, words, bursts)  # fmt: skip
    assert reached


def _sweep(n: int) -> list[tuple[tuple[int, ...], tuple[int, ...]]]:
    """(periods, start phases) per run for N clocks. First equal periods with the clocks out of
    phase; then each ratio both ways, assigned by the bits of each clock's index, so every pair
    of clocks sees each ratio in some run (two indices differ in at least one bit)."""
    runs = [((10,) * n, tuple(3 * i for i in range(n)))]
    for a, b in ((10, 30), (10, 7)):
        for bit in range(max(1, (n - 1).bit_length())):
            for lo, hi in ((a, b), (b, a)):
                runs.append((tuple(hi if i >> bit & 1 else lo for i in range(n)), ()))
    return runs


async def traffic_crosses_clock_domains_at_every_ratio(dut: Any) -> None:
    """With traffic that crosses clock domains: for each run of _sweep (equal periods out of
    phase, then 1:3, 3:1, 10:7 and 7:10 between every pair of clocks), the clocks restart at
    those periods with reset held around the change, then all masters at once and the AXI4
    bursts. A crossing that loses or repeats a transfer at some ratio returns wrong data or
    times out."""
    masters, slaves, clocks = await _bring_up(dut)
    crossing = crossing_masters(SPEC)
    assert crossing, "no master's traffic crosses a clock domain"
    for periods, phases in _sweep(len(SPEC.clocks)):
        _set_resets(dut, True)
        _start_clocks(dut, periods, phases)
        await _reset_everything(dut, masters, slaves, clocks)
        total, count = await _traffic(masters)
        bursts = await _bursts(masters)
        dut._log.info("clocks at %s ns, phases %s: %d words over %d masters (%s cross), %d bursts",
                      periods, phases, total, count, crossing, bursts)  # fmt: skip


async def shared_buses_block_behind_a_stalled_slave_and_crossbars_do_not(dut: Any) -> None:
    """Master A's read waits at slave X, stalled; master B then reads slave Y. On a shared bus
    A's request holds the head of the one path to the slaves, so B must wait for X (the cost of
    the topology, not a bug); on a crossbar B must finish while X is stalled. Then X opens and
    both complete, with the right data."""
    masters, slaves, clocks = await _bring_up(dut)
    checked = 0
    for f in SPEC.fabrics:
        found = blocking_path(SPEC, f)
        if found is None:
            continue
        a, x, word_a, (b, y, word_b) = found
        data_a, data_b = random.getrandbits(32), random.getrandbits(32)
        assert await masters[a.name].write(word_a, data_a) == 0
        assert await masters[b.name].write(word_b, data_b) == 0
        slaves[x.name].stall(True)
        read_a = cocotb.start_soon(masters[a.name].read(word_a))
        await ClockCycles(clocks[f.domain], 40)
        n = len(slaves[y.name].log)
        read_b = cocotb.start_soon(masters[b.name].read(word_b))
        await ClockCycles(clocks[f.domain], 200)
        where = f"{f.name}: {b.name} -> {y.name} with {a.name} -> {x.name} stalled"
        assert not read_a.done(), f"{f.name}: {a.name} finished through a stalled {x.name}"
        if f.topology == "shared-bus":
            assert not read_b.done() and len(slaves[y.name].log) == n, f"{where}: it did not wait"
        else:
            assert read_b.done(), f"{where}: blocked on a crossbar"
        slaves[x.name].stall(False)
        await Combine(read_a, read_b)
        assert read_a.result().data == data_a, f"{f.name}: {a.name} read"
        assert read_b.result().data == data_b, f"{f.name}: {b.name} read"
        checked += 1
    assert checked > 0
    dut._log.info("head-of-line: %d fabrics", checked)


async def slave_decerr_returns_as_the_model_says(dut: Any) -> None:
    """Every master to every AXI slave it reaches: the slave answers DECERR, which only the
    fabric normally does. An AXI master gets the code the path leaves it (_expected_resp);
    AHB-Lite and APB masters get their one error. Afterwards the same word works again."""
