"""Shared rendering helpers: the Jinja environment, the file header and SV literals."""

import hashlib
import re
from functools import cache
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from hdl_bag import __version__
from hdl_bag.ir import Spec, dumps


@cache
def environment(root: Path) -> Environment:
    """Jinja environment for templates under ROOT: strict, deterministic, LF output."""
    return Environment(
        loader=FileSystemLoader(str(root)),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        autoescape=False,
    )


def ir_sha256(spec: Spec) -> str:
    return hashlib.sha256(dumps(spec).encode("utf-8")).hexdigest()


def header(spec: Spec, user_header: str | None, comment: str = "//") -> str:
    """D4: the user's File header text verbatim, then the tool banner. No timestamp."""
    rule = f"{comment} " + "-" * 76
    banner = [
        rule,
        f"{comment} Generated by hdl-bag {__version__} (bag). DO NOT EDIT.",
        f"{comment} Project: {spec.project.name}   Revision: {spec.project.revision or '-'}",
        f"{comment} IR sha256: {ir_sha256(spec)}",
        rule,
    ]
    text = ""
    if user_header:
        text = user_header.replace("\r\n", "\n")
        if not text.endswith("\n"):
            text += "\n"
    return text + "\n".join(banner) + "\n"


def lit(width: int, value: int) -> str:
    """Sized SV literal; -1 means all ones."""
    value = (1 << width) - 1 if value == -1 else value & ((1 << width) - 1)
    if width <= 4:
        return f"{width}'b{value:0{width}b}"
    digits = f"{value:0{(width + 3) // 4}X}"
    if len(digits) > 4:  # group by 4 from the right: 32'h1000_3000
        head = len(digits) % 4 or 4
        digits = "_".join([digits[:head], *re.findall(".{4}", digits[head:])])
    return f"{width}'h{digits}"


def camel(name: str) -> str:
    """snake_case identifier -> CamelCase (localparam style)."""
    return "".join(part[:1].upper() + part[1:] for part in name.split("_") if part)
